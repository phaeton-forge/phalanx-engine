import {
  at,
  crashPeer,
  disconnect,
  faults,
  range,
  reconnect,
  replaceWithBot,
  restartServer,
  returnFromBot,
  scenario,
  type Scenario,
} from '../dsl/scenario.js';

const SLOTS = ['human', 'human', 'bot:aggressive'] as const;
const PEERS = ['A', 'B'] as const;

/**
 * Stage A scenarios. Fault drops catch up from the authoritative log
 * at the end of the range (`FaultGate.retransmit`), not by a wire resend.
 */
export function catalog(): readonly Scenario[] {
  return [
    scenario('reconnect-snapshot-mid-fight', {
      suite: 'disconnect',
      tags: ['disconnect', 'quick'],
      seed: 42,
      ticks: 40,
      slots: [...SLOTS],
      peers: [...PEERS],
      timeline: [
        at(8, disconnect('B')),
        at(14, reconnect('B', 'snapshot')),
        range(
          18,
          26,
          faults('B', { delay: [0, 3], dup: 0.05, reorder: 0.1, drop: 0.02 })
        ),
        at(30, crashPeer('B')),
        at(34, reconnect('B', 'log')),
        at(36, replaceWithBot('B', 'defensive')),
        at(37, returnFromBot('B')),
        at(38, restartServer()),
      ],
      inputs: 'scripted:basic',
      expect: { converge: true },
    }),
    scenario('reconnect-via-snapshot', {
      suite: 'disconnect',
      tags: ['disconnect', 'quick'],
      seed: 7,
      ticks: 16,
      slots: ['human', 'bot:defensive'],
      peers: [...PEERS],
      timeline: [at(4, disconnect('B')), at(8, reconnect('B', 'snapshot'))],
      inputs: 'scripted:basic',
      expect: { converge: true },
    }),
    scenario('reconnect-via-log', {
      suite: 'disconnect',
      tags: ['disconnect', 'quick'],
      seed: 8,
      ticks: 16,
      slots: ['human', 'bot:aggressive'],
      peers: [...PEERS],
      timeline: [at(3, disconnect('B')), at(9, reconnect('B', 'log'))],
      inputs: 'bots',
      expect: { converge: true },
    }),
    scenario('crash-reconnect-log', {
      suite: 'disconnect',
      tags: ['disconnect', 'quick'],
      seed: 9,
      ticks: 16,
      slots: ['human', 'bot:aggressive'],
      peers: [...PEERS],
      timeline: [at(5, crashPeer('B')), at(10, reconnect('B', 'log'))],
      inputs: 'scripted:basic',
      expect: { converge: true },
    }),
    scenario('fault-range', {
      suite: 'disconnect',
      tags: ['disconnect', 'quick'],
      seed: 11,
      ticks: 20,
      slots: ['human:0', 'bot:defensive'],
      peers: [...PEERS],
      timeline: [
        range(
          4,
          12,
          faults('B', { delay: [0, 2], dup: 0.1, reorder: 0.2, drop: 0.05 })
        ),
      ],
      inputs: 'scripted:basic',
      expect: { converge: true },
    }),
    scenario('controller-handoff', {
      suite: 'disconnect',
      tags: ['disconnect', 'quick'],
      seed: 1,
      ticks: 4,
      slots: ['human', 'bot:aggressive'],
      peers: ['A'],
      timeline: [
        at(1, replaceWithBot('A', 'defensive')),
        at(2, returnFromBot('A')),
      ],
      inputs: 'bots',
      expect: { converge: true },
      requires: ['setController'],
    }),
    scenario('restart-server', {
      suite: 'disconnect',
      tags: ['disconnect'],
      seed: 1,
      ticks: 4,
      slots: ['human'],
      peers: ['A'],
      timeline: [at(1, restartServer())],
      inputs: 'bots',
      expect: { converge: true },
      requires: ['restartServer'],
    }),
    scenario('round-trip-sweep', {
      suite: 'save-restore',
      tags: ['save-restore', 'quick'],
      seed: 21,
      ticks: 18,
      slots: ['human', 'bot:aggressive', 'bot:defensive:0'],
      peers: ['A'],
      timeline: [
        at(4, { op: 'roundTrip', peer: 'A' }),
        at(10, { op: 'roundTrip', peer: 'A' }),
        at(15, { op: 'roundTrip', peer: 'A' }),
      ],
      inputs: 'scripted:basic',
      expect: { converge: true },
    }),
    scenario('round-trip-populated', {
      suite: 'save-restore',
      tags: ['save-restore', 'quick'],
      seed: 22,
      ticks: 12,
      slots: ['human', 'bot:aggressive'],
      peers: ['A'],
      timeline: [at(6, { op: 'roundTrip', peer: 'A' })],
      inputs: 'scripted:basic',
      expect: { converge: true },
      options: { spawnOnRestore: true },
    }),
    scenario('legacy-spawn-with-id', {
      suite: 'save-restore',
      tags: ['save-restore', 'quick'],
      seed: 23,
      ticks: 8,
      slots: ['human', 'bot:defensive'],
      peers: ['A'],
      timeline: [at(3, { op: 'restoreSelf', peer: 'A' })],
      inputs: 'bots',
      expect: { failsWith: 'spawnWithId: entity' },
      options: { legacySpawnWithId: true },
    }),
    scenario('malformed-envelope', {
      suite: 'adversarial',
      tags: ['adversarial', 'quick'],
      seed: 31,
      ticks: 10,
      slots: ['human', 'bot:aggressive'],
      peers: [...PEERS],
      timeline: [at(2, { op: 'malformed', peer: 'A' })],
      inputs: 'scripted:basic',
      expect: { converge: true },
    }),
    scenario('throwing-bot', {
      suite: 'adversarial',
      tags: ['adversarial', 'quick'],
      seed: 32,
      ticks: 10,
      slots: ['human', 'bot:aggressive'],
      peers: ['A'],
      timeline: [at(2, { op: 'throwBot' })],
      inputs: 'bots',
      expect: { converge: true },
    }),
    scenario('throwing-system', {
      suite: 'adversarial',
      tags: ['adversarial', 'quick'],
      seed: 33,
      ticks: 8,
      slots: ['human', 'bot:defensive'],
      peers: ['A'],
      timeline: [at(3, { op: 'throwSystem' })],
      inputs: 'bots',
      expect: { failsWith: 'skirmish tick exploded' },
    }),
    scenario('pause-resume', {
      suite: 'adversarial',
      tags: ['adversarial', 'quick'],
      seed: 34,
      ticks: 12,
      slots: ['human', 'bot:aggressive'],
      peers: [...PEERS],
      timeline: [at(3, { op: 'pause' }), at(6, { op: 'resume' })],
      inputs: 'scripted:basic',
      expect: { converge: true },
    }),
    scenario('restore-while-running', {
      suite: 'adversarial',
      tags: ['adversarial', 'quick'],
      seed: 35,
      ticks: 12,
      slots: ['human', 'bot:aggressive'],
      peers: ['A'],
      timeline: [at(5, { op: 'restoreSelf', peer: 'A' })],
      inputs: 'scripted:basic',
      // Restore truncates the command log, so the oracle cannot replay
      // ticks that happen after it. The event itself checks the digest.
      expect: { converge: false },
    }),
    scenario('schema-change', {
      suite: 'adversarial',
      tags: ['adversarial', 'quick'],
      seed: 36,
      ticks: 8,
      slots: ['human', 'bot:defensive'],
      peers: ['A'],
      timeline: [at(3, { op: 'schemaChange', peer: 'A' })],
      inputs: 'bots',
      expect: { failsWith: 'formatVersion is newer' },
    }),
    scenario('pool-lifecycle', {
      suite: 'pool-lifecycle',
      tags: ['pool-lifecycle', 'quick'],
      seed: 41,
      ticks: 4,
      slots: ['human', 'bot:aggressive'],
      peers: ['A'],
      timeline: [],
      inputs: 'bots',
      expect: { converge: false },
      options: { poolProbe: true },
      knownFailure:
        'Pool return must restore GAS attributes, granted abilities and initComponent tags to a fresh spawn.',
    }),
    scenario('tick-limit-draw', {
      suite: 'disconnect',
      tags: ['quick'],
      seed: 51,
      ticks: 8,
      slots: ['human', 'bot:defensive:0'],
      peers: ['A'],
      timeline: [],
      inputs: 'bots',
      expect: { converge: true },
      options: { tickLimit: 5 },
    }),
  ];
}
